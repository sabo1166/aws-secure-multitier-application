"""Data for the /roadmap and /architecture pages.

roadmap.json is generated by tools/build-roadmap.mjs from the project's status files, so the page can only
show progress that the evidence register supports. architecture.json is authored by hand and checked against
docs/architecture.md by tools/check-docs.mjs. Both are read once and cached.
"""
from __future__ import annotations

import json
from functools import lru_cache

from .paths import DATA_DIR


@lru_cache(maxsize=None)
def _load(name: str) -> dict:
    return json.loads((DATA_DIR / name).read_text(encoding="utf-8"))


def roadmap() -> dict:
    data = _load("roadmap.json")
    tasks = [t for p in data["phases"] for t in p["tasks"]]
    totals = {k: sum(1 for t in tasks if t["status"] == k) for k in ("completed", "in_progress", "planned", "blocked")}
    return {**data, "task_totals": {**totals, "all": len(tasks)}}


def architecture() -> dict:
    data = _load("architecture.json")
    zones = {z["id"]: z for z in data["zones"]}
    return {**data, "zone_by_id": zones, "component_by_id": {c["id"]: c for c in data["components"]}}
